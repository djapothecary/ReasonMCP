using System.ComponentModel;
using System.Text;
using DocumentFormat.OpenXml.Wordprocessing;
using Microsoft.Extensions.AI;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.VectorData;
using Microsoft.SemanticKernel;
using ModelContextProtocol.Server;
using ReasonMCP.Models;

namespace ReasonMCP.Tools
{
    /// <summary>
    /// Exposes the SQLite Vector store to Reason via MCP for semantic knowledge retrieval.
    /// </summary>
    public class DocumentContextSearchTool
    {
        private readonly VectorStoreCollection<string, DocumentVectorModel> _collection;
        private readonly IEmbeddingGenerator<string, Embedding<float>> _embeddingGenerator;
        private readonly ILogger<DocumentContextSearchTool> _logger;

        public DocumentContextSearchTool(
            VectorStoreCollection<string, DocumentVectorModel> collection,
            IEmbeddingGenerator<string, Embedding<float>> embeddingGenerator,
            ILogger<DocumentContextSearchTool> logger
        )
        {
            _collection = collection;
            _embeddingGenerator = embeddingGenerator;
            _logger = logger;
        }

        /// <summary>
        /// Searches the ingested codebase and ADRs for relevant context.
        /// NOTE: Add your specific MCP tool attribute here (e.g.,[McpTool("documents_context")] or [KernelFunction])
        /// depending on the exact MCP SDK library you are utilizing.
        /// </summary>
        /// <param name="query">The semantic search query generated by Reason.</param>
        /// <param name="maxResults">The maximum number of chunks to return (defaults to 5 to protect token limits).</param>
        [McpServerTool(Name = "document_context_search")]
        [KernelFunction("document_context_search")]
        [Description("Allows the Reason AI coding agent to search the vector store for additional infomation to answer a query.")]
        public async Task<string> SearchDocumentsContextAsync(
            [Description("The query to use for searching the documents_context vector store")] string query,
            [Description("The maximum number of query results")] int maxResults = 5,
            [Description("Cancellation Token")] CancellationToken cancellationToken = default
        )
        {
            //  1.  Gaurd Clause
            if (string.IsNullOrWhiteSpace(query))
            {
                return "Search query was empty.  Please provide a specific technical topic to search.";
            }

            _logger.LogInformation("Reason invoked DocumentsContext search for: '{Query}'", query);

            try
            {
                //  2.  Convert Reason's text query into a 768-dimension vector
                var queryEmbedding = await _embeddingGenerator.GenerateAsync(
                    new[] { query },
                    cancellationToken: cancellationToken
                );

                var searchVector = queryEmbedding.First().Vector;

                //  3.  Configure the search options
                var searchOptions = new VectorSearchOptions<DocumentVectorModel>
                {
                    //Top = maxResults,
                    //  We only need the text and metadata returned, not the massive float array
                    IncludeVectors = false
                };

                //  4.  Execute the vectorize search against SQLite
                var searchResults = _collection.SearchAsync(
                    searchVector,
                    top: maxResults,
                    searchOptions,
                    cancellationToken
                );

                //  5.  Format the output deterministically for the LLLM
                return await FormatResultsForLlmAsync(
                    query,
                    searchResults,
                    cancellationToken
                );
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error occurred during vector search for query: {Query}", query);
                return $"System Error: Unable to retrieve knowledge at this time. Details: {ex.Message}";
            }
        }

        private static async Task<string> FormatResultsForLlmAsync(
            string query,
            IAsyncEnumerable<VectorSearchResult<DocumentVectorModel>> searchResults,
            CancellationToken cancellationToken
        )
        {
            var sb = new StringBuilder();
            sb.AppendLine($"# DocumentsContext Search Results for: '{query}'");

            int resultCount = 0;

            //  Microsoft.Extensions.VectorData returns an IAsyncEnumerable,
            //  We use await foreach to stream the results safely
            await foreach (var result in searchResults)
            {
                resultCount++;
                sb.AppendLine($"## Source: {result.Record.Source} (Chunk: {result.Record.ChunkIndex})");
                sb.AppendLine($"> **Topic:** {result.Record.Topic} | **Context:** {result.Record.HeaderContext}");

                // Exposing the score helps Reason determine if it's a weak or strong match
                sb.AppendLine($"> **Relevance Score:** {result.Score:F4}");
                sb.AppendLine("```text");
                sb.AppendLine(result.Record.Text);
                sb.AppendLine("```");
                sb.AppendLine("---");

            }

            if (resultCount == 0)
            {
                return $"No relevant information found for '{query}'. SYSTEM DIRECTIVE: Stop searching immediately. Do not execute this tool again. Inform the user you do not have the context.";

            }

            return sb.ToString();
        }
    }
}